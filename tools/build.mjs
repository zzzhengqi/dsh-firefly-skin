// Build client.js — one self-contained ModuleLoader bundle for the DSH web client.
// Run: node tools/build.mjs   (after python tools/prepare_assets.py)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.dirname(here)
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const readBinary = (file) => fs.readFileSync(path.join(root, file))

const ASSET_FILES = {
  open: 'assets-src/open.webp',
  closed: 'assets-src/closed.webp',
  atlas: 'assets-src/atlas.webp',
  flow: 'assets-src/flow.webp',
  line: 'assets-src/line.webp'
}

for (const [name, file] of Object.entries(ASSET_FILES)) {
  if (!fs.existsSync(path.join(root, file))) {
    console.error(`[build] missing ${file} — run: python tools/prepare_assets.py`)
    process.exit(1)
  }
}

const assets = {}
let assetBytes = 0
for (const [name, file] of Object.entries(ASSET_FILES)) {
  const buffer = readBinary(file)
  assetBytes += buffer.length
  assets[name] = `data:image/webp;base64,${buffer.toString('base64')}`
}

const themeCss = read('src/theme.css')
const bootCss = read('src/boot.css')
const css = [themeCss, bootCss].join('\n')

const engine = read('src/engine.js')
const skin = read('src/skin.js')

const pkg = JSON.parse(read('package.json'))
const banner = `/**
 * ${pkg.name} v${pkg.version} — browser half.
 * Firefly (流萤) skin for the DeepSeek Harness web client:
 * boot film, night palette, ambient fireflies and a replay control.
 *
 * Generated by tools/build.mjs — edit src/ instead.
 * Portrait, eye atlas, hair-flow map and line art derive from
 * Firefly-UI-animation v1.2.0 (Qoder skin handoff package).
 */`

const bundle = `${banner}
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    const module = { exports: {} }
    const ASSETS = ${JSON.stringify(assets, null, 0)}
    const CSS = ${JSON.stringify(css)}

${engine}

${skin}

    return module.exports
  }
})
`

const target = path.join(root, 'client.js')
fs.writeFileSync(target, bundle, 'utf8')
const kib = (n) => `${(n / 1024).toFixed(1)} KiB`
console.log(`[build] ${path.relative(process.cwd(), target)}  ${kib(Buffer.byteLength(bundle))}`)
console.log(`[build] assets ${kib(assetBytes)} → inlined ${kib(Buffer.byteLength(JSON.stringify(assets)))}; css ${kib(Buffer.byteLength(css))}`)
